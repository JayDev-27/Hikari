// Generates src/generated.ts from schema/protocol.schema.json.
// Zero dependencies on purpose: the schema uses a small JSON-Schema subset
// (object/array/enum/const/string/number/integer/boolean/$ref/{}), which we map directly.
// Python side (Person B) generates Pydantic models from the same file
// (datamodel-code-generator). Run: node scripts/gen-ts.mjs [--check]
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const schema = JSON.parse(readFileSync(join(root, "schema/protocol.schema.json"), "utf8"));
const defs = schema.$defs;

const tsType = (s) => {
  if (!s || Object.keys(s).length === 0) return "unknown";
  if (s.$ref) return s.$ref.split("/").pop();
  if (s.const !== undefined) return JSON.stringify(s.const);
  if (s.enum) return s.enum.map((e) => JSON.stringify(e)).join(" | ");
  switch (s.type) {
    case "string": return "string";
    case "number": case "integer": return "number";
    case "boolean": return "boolean";
    case "array": return `Array<${tsType(s.items)}>`;
    case "object": {
      if (!s.properties) return "Record<string, unknown>";
      const req = new Set(s.required ?? []);
      const body = Object.entries(s.properties).map(([k, v]) => {
        const doc = v.description ? `  /** ${v.description} */\n` : "";
        return `${doc}  ${k}${req.has(k) ? "" : "?"}: ${tsType(v)};`;
      });
      return `{\n${body.join("\n")}\n}`;
    }
    default: return "unknown";
  }
};

let out = `// AUTO-GENERATED by packages/protocol/scripts/gen-ts.mjs — do not edit.\n`;
out += `export const PROTOCOL_VERSION = ${JSON.stringify(schema["x-protocolVersion"])} as const;\n\n`;
for (const [name, def] of Object.entries(defs)) {
  if (name === "Envelope") continue;
  const t = tsType(def);
  out += t.startsWith("{") ? `export interface ${name} ${t}\n\n` : `export type ${name} = ${t};\n\n`;
}
const map = schema["x-payloads"];
out += `export interface PayloadMap {\n`;
for (const [type, def] of Object.entries(map)) out += `  ${JSON.stringify(type)}: ${def};\n`;
out += `}\n\n`;
out += `export interface Envelope<T extends MessageType = MessageType> {
  v: typeof PROTOCOL_VERSION;
  type: T;
  id?: string;
  replyTo?: string;
  turnId?: string;
  ts: number;
  payload: PayloadMap[T];
}

/** Discriminated union of every concrete message. */
export type AnyMessage = { [K in MessageType]: Envelope<K> }[MessageType];
`;

const target = join(root, "src/generated.ts");
if (process.argv.includes("--check")) {
  const cur = readFileSync(target, "utf8");
  if (cur !== out) { console.error("generated.ts is stale: run pnpm -F @hikari/protocol gen"); process.exit(1); }
  console.log("protocol types up to date");
} else {
  writeFileSync(target, out);
  console.log("wrote", target);
}
