//! Menu-bar (tray) icon. Hikari runs as an accessory app (no Dock icon) unless
//! "Show in Dock" is checked (see `dock`).

use tauri::menu::{CheckMenuItem, Menu, MenuItem, PredefinedMenuItem};
use tauri::tray::TrayIconBuilder;
use tauri::{AppHandle, Emitter, Manager, Runtime};

use crate::stage::{self, STAGE};

/// Tray "Mute mic" item, kept so the ⌘⇧M hotkey can update its check mark.
pub struct MuteItem<R: Runtime>(pub CheckMenuItem<R>);

/// Single source of truth for mic mute (tray click and ⌘⇧M both land here).
pub fn set_muted<R: Runtime>(app: &AppHandle<R>, muted: bool) {
    if let Some(item) = app.try_state::<MuteItem<R>>() {
        let _ = item.0.set_checked(muted);
    }
    let _ = app.emit("hotkey://mute", muted);
}

pub fn toggle_muted<R: Runtime>(app: &AppHandle<R>) {
    let now = app
        .try_state::<MuteItem<R>>()
        .and_then(|i| i.0.is_checked().ok())
        .unwrap_or(false);
    set_muted(app, !now);
}

/// Tray "Hide/Show Hikari" item, kept so a Dock-icon click can relabel it.
pub struct ToggleItem<R: Runtime>(pub MenuItem<R>);

/// Show or hide the stage and keep the tray label, poll state and frontend in sync.
pub fn set_stage_visible<R: Runtime>(app: &AppHandle<R>, visible: bool) {
    let Some(w) = app.get_webview_window(STAGE) else {
        return;
    };
    app.state::<std::sync::Arc<stage::StageState>>()
        .visible
        .store(visible, std::sync::atomic::Ordering::Relaxed);
    if visible {
        #[cfg(target_os = "macos")]
        crate::dock::reshow_stage(app);
        #[cfg(not(target_os = "macos"))]
        let _ = w.show();
    } else {
        let _ = w.hide();
    }
    // Frontend pauses its render loop while hidden.
    let _ = app.emit_to(STAGE, "stage://visible", visible);
    if let Some(item) = app.try_state::<ToggleItem<R>>() {
        let _ = item
            .0
            .set_text(if visible { "Hide Hikari" } else { "Show Hikari" });
    }
}

pub fn setup<R: Runtime>(app: &AppHandle<R>, show_in_dock: bool) -> tauri::Result<()> {
    let toggle = MenuItem::with_id(app, "toggle", "Hide Hikari", true, None::<&str>)?;
    let chat = MenuItem::with_id(app, "chat", "Chat…", true, None::<&str>)?;
    let studio = MenuItem::with_id(app, "studio", "Character Studio…", true, None::<&str>)?;
    let lock =
        CheckMenuItem::with_id(app, "lock", "Click-through lock", true, false, None::<&str>)?;
    let mute = CheckMenuItem::with_id(app, "mute", "Mute mic", true, false, None::<&str>)?;
    let dock = CheckMenuItem::with_id(
        app,
        "dock",
        "Show in Dock",
        true,
        show_in_dock,
        None::<&str>,
    )?;
    let panic = MenuItem::with_id(
        app,
        "panic",
        "Stop all actions",
        true,
        Some("CmdOrCtrl+Shift+Escape"),
    )?;
    let quit = MenuItem::with_id(app, "quit", "Quit Hikari", true, Some("CmdOrCtrl+Q"))?;
    let menu = Menu::with_items(
        app,
        &[
            &toggle,
            &chat,
            &studio,
            &PredefinedMenuItem::separator(app)?,
            &lock,
            &mute,
            &dock,
            &PredefinedMenuItem::separator(app)?,
            &panic,
            &PredefinedMenuItem::separator(app)?,
            &quit,
        ],
    )?;

    let lock_c = lock.clone();
    let mute_c = mute.clone();
    let dock_c = dock.clone();
    app.manage(MuteItem(mute.clone()));
    app.manage(ToggleItem(toggle.clone()));
    TrayIconBuilder::with_id("hikari")
        // Monochrome sakura (black + alpha) as a macOS template image: the system
        // tints it for light/dark menu bars like other status items. Generated by
        // assets/brand/tray.swift from the app logo.
        .icon(tauri::image::Image::from_bytes(include_bytes!(
            "../icons/tray/tray-template@2x.png"
        ))?)
        .icon_as_template(true)
        .tooltip("Hikari")
        .menu(&menu)
        .show_menu_on_left_click(true)
        .on_menu_event(move |app, ev| match ev.id().as_ref() {
            "toggle" => {
                if let Some(w) = app.get_webview_window(STAGE) {
                    set_stage_visible(app, !w.is_visible().unwrap_or(true));
                }
            }
            "chat" | "studio" => {
                if let Err(e) = crate::windows::show(app, ev.id().as_ref()) {
                    log::warn!("show window: {e}");
                }
            }
            "lock" => stage::set_locked(app, lock_c.is_checked().unwrap_or(false)),
            // The menu already flipped the check mark; broadcast the new value.
            "mute" => set_muted(app, mute_c.is_checked().unwrap_or(false)),
            "dock" => crate::dock::set_shown(app, dock_c.is_checked().unwrap_or(false)),
            "panic" => {
                let _ = app.emit("hotkey://panic", ());
            }
            "quit" => app.exit(0),
            _ => {}
        })
        .build(app)?;
    Ok(())
}
